const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const {dailyRows,rankedQueues}=require('../inbound-chart-data.js');
const snapshot=JSON.parse(fs.readFileSync(path.join(root,'data/inbound-operations-snapshot.json')));
const registry=JSON.parse(fs.readFileSync(path.join(root,'data/inbound-operations-registry.json')));
const ids=['primary_incoming','primary_answered','abandoned_total','primary_abandoned','non_primary_abandoned','service_level_20','abandonment_rate'];
const rows=dailyRows(snapshot,ids,registry.metrics);
assert.equal(rows.length,4);
for(const id of ids.slice(0,5))assert.equal(rows.reduce((sum,r)=>sum+r.values[id],0),snapshot.totals[id].value);
for(const r of rows)assert.equal(r.values.primary_abandoned+r.values.non_primary_abandoned,r.values.abandoned_total);
assert.equal(rows[3].values.primary_incoming,0,'Explicit zero must remain zero');
assert.equal(rows[3].values.service_level_20,95,'Daily rate is native, not reconstructed');
const missing=structuredClone(snapshot);
missing.daily=missing.daily.filter(p=>p.id!=='primary_abandoned');
for(const r of dailyRows(missing,ids,registry.metrics))assert.equal(r.values.non_primary_abandoned,null,'Missing operand must not become zero');
const negative=structuredClone(snapshot);
negative.daily=negative.daily.map(p=>p.id==='primary_abandoned'?{...p,value:999999}:p);
assert(dailyRows(negative,ids,registry.metrics).every(r=>r.values.non_primary_abandoned===null));
const duplicate=structuredClone(snapshot);
duplicate.daily.push(duplicate.daily.find(p=>p.id==='service_level_20'));
assert(dailyRows(duplicate,ids,registry.metrics).some(r=>r.values.service_level_20===null),'Duplicate native rates must not be summed');
const ranked=rankedQueues(snapshot);
assert.equal(ranked.length,6);assert.equal(ranked[0].value,402);
assert(ranked.every((r,i)=>i===0||ranked[i-1].value>=r.value));
assert.equal(rankedQueues({...snapshot,by_queue:{x:{abandoned_total:null},y:{abandoned_total:0}}}).length,1);
const single=dailyRows({...snapshot,end:snapshot.start},ids,registry.metrics);assert.equal(single.length,1);
console.log('PASS: daily native counts/rates, abandonment stack totals, missing/negative/duplicate inputs, single-day scope and top-six ranking.');
